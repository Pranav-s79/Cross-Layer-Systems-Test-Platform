"""Deterministic, terminating RV32I programs for seeded differential tests."""

from __future__ import annotations

import random

_WORK_REGISTERS = tuple(f"x{i}" for i in range(5, 16) if i != 8)
_BINARY_OPS = ("add", "sub", "sll", "slt", "sltu", "xor", "srl", "sra", "or", "and")
_IMMEDIATE_OPS = ("addi", "slti", "sltiu", "xori", "ori", "andi")
_SHIFT_OPS = ("slli", "srli", "srai")
_MEMORY_BYTES = 64 * 1024
_SCRATCH_BASE = 0x4000
_SCRATCH_BYTES = 256


def generate(seed: int, *, instructions: int = 300) -> str:
    """Return a reproducible, bounded RV32I assembly program.

    Random instructions operate only on initialized registers and a dedicated
    aligned scratch area. Control flow is deliberately kept linear: fuzzing
    instruction semantics should not introduce accidental infinite loops or
    accesses outside the testbench's memory.
    """
    if isinstance(seed, bool) or not isinstance(seed, int):
        raise TypeError("seed must be an integer")
    if isinstance(instructions, bool) or not isinstance(instructions, int) or instructions < 1:
        raise ValueError("instructions must be a positive integer")
    if _SCRATCH_BASE + _SCRATCH_BYTES > _MEMORY_BYTES:
        raise AssertionError("random-program scratch area exceeds testbench memory")

    rng = random.Random(seed)
    lines = [
        f"# Generated by CrossLayer with seed {seed}.",
        ".text",
        ".globl _start",
        "_start:",
        f"    li s0, {_SCRATCH_BASE}",
    ]
    for register in _WORK_REGISTERS:
        lines.append(f"    li {register}, {rng.randrange(0, 1 << 32)}")

    for _ in range(instructions):
        choice = rng.randrange(5)
        rd = rng.choice(_WORK_REGISTERS)
        rs1 = rng.choice(_WORK_REGISTERS)
        if choice == 0:
            op = rng.choice(_BINARY_OPS)
            rs2 = rng.choice(_WORK_REGISTERS)
            lines.append(f"    {op} {rd}, {rs1}, {rs2}")
        elif choice == 1:
            op = rng.choice(_IMMEDIATE_OPS)
            lines.append(f"    {op} {rd}, {rs1}, {rng.randint(-2048, 2047)}")
        elif choice == 2:
            op = rng.choice(_SHIFT_OPS)
            lines.append(f"    {op} {rd}, {rs1}, {rng.randrange(32)}")
        elif choice == 3:
            offset = 4 * rng.randrange(_SCRATCH_BYTES // 4)
            lines.append(f"    sw {rs1}, {offset}(s0)")
        else:
            offset = 4 * rng.randrange(_SCRATCH_BYTES // 4)
            lines.append(f"    lw {rd}, {offset}(s0)")

    lines.extend(
        [
            "    li t0, 0x10000000",
            "    sw x5, 0(t0)",
            "    ebreak",
            "",
        ]
    )
    return "\n".join(lines)
