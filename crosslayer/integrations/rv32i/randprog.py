"""Deterministic, terminating RV32I programs for seeded differential tests."""

from __future__ import annotations

import random

_WORK_REGISTERS = tuple(f"x{i}" for i in range(5, 16) if i != 8)
_JUMP_BASE = "x16"
"""Holds the PC for an AUIPC + JALR pair; never a work register."""
_BINARY_OPS = ("add", "sub", "sll", "slt", "sltu", "xor", "srl", "sra", "or", "and")
_IMMEDIATE_OPS = ("addi", "slti", "sltiu", "xori", "ori", "andi")
_SHIFT_OPS = ("slli", "srli", "srai")
_LOADS = {"lb": 1, "lbu": 1, "lh": 2, "lhu": 2, "lw": 4}
_STORES = {"sb": 1, "sh": 2, "sw": 4}
_BRANCHES = ("beq", "bne", "blt", "bge", "bltu", "bgeu")
_MEMORY_BYTES = 64 * 1024
_SCRATCH_BASE = 0x4000
_SCRATCH_BYTES = 256
_OUT_ADDR = 0x1000_0000
_WEIGHTS = {"alu": 6, "imm": 4, "shift": 2, "upper": 1, "load": 3, "store": 3, "branch": 3, "jal": 1, "jalr": 1}


def generate(seed: int, *, instructions: int = 300) -> str:
    """Return a reproducible, bounded RV32I assembly program.

    Every working register is initialized first. Data accesses stay inside an
    aligned scratch area and are naturally aligned for their width (each byte
    offset a width allows is used). Control flow only goes forward: branches
    and jumps skip 0-3 instructions, and JALR jumps over one instruction via
    AUIPC, so every program terminates. A quarter of the branches compare a
    register with itself, so every branch is both taken and not taken across
    seeds. All working registers are XOR-folded into the single output value,
    so any wrong result reaches the output port, and EBREAK ends the program.
    ECALL is never generated (it would end the run early).

    ``instructions`` counts generated body items; a branch or jump item also
    emits the instructions it skips.
    """
    if isinstance(seed, bool) or not isinstance(seed, int):
        raise TypeError("seed must be an integer")
    if isinstance(instructions, bool) or not isinstance(instructions, int) or instructions < 1:
        raise ValueError("instructions must be a positive integer")
    if _SCRATCH_BASE + _SCRATCH_BYTES > _MEMORY_BYTES:
        raise AssertionError("random-program scratch area exceeds testbench memory")

    rng = random.Random(seed)
    kinds = list(_WEIGHTS)
    weights = list(_WEIGHTS.values())
    lines = [
        f"# Generated by CrossLayer with seed {seed}.",
        ".text",
        ".globl _start",
        "_start:",
        f"    li s0, {_SCRATCH_BASE}",
    ]
    for register in _WORK_REGISTERS:
        lines.append(f"    li {register}, {rng.randrange(0, 1 << 32)}")

    def reg() -> str:
        return rng.choice(_WORK_REGISTERS)

    def straight() -> str:
        """One instruction that never changes control flow or touches memory."""
        return f"    {rng.choice(_BINARY_OPS)} {reg()}, {reg()}, {reg()}"

    labels = 0
    for _ in range(instructions):
        kind = rng.choices(kinds, weights)[0]
        if kind == "alu":
            lines.append(f"    {rng.choice(_BINARY_OPS)} {reg()}, {reg()}, {reg()}")
        elif kind == "imm":
            lines.append(f"    {rng.choice(_IMMEDIATE_OPS)} {reg()}, {reg()}, {rng.randint(-2048, 2047)}")
        elif kind == "shift":
            lines.append(f"    {rng.choice(_SHIFT_OPS)} {reg()}, {reg()}, {rng.randrange(32)}")
        elif kind == "upper":
            lines.append(f"    {rng.choice(('lui', 'auipc'))} {reg()}, {rng.randrange(1 << 20)}")
        elif kind in ("load", "store"):
            op, size = rng.choice(list((_LOADS if kind == "load" else _STORES).items()))
            offset = size * rng.randrange(_SCRATCH_BYTES // size)
            lines.append(f"    {op} {reg()}, {offset}(s0)")
        elif kind == "branch":
            rs1 = reg()
            rs2 = rs1 if rng.random() < 0.25 else reg()
            label = f"L{labels}"
            labels += 1
            lines.append(f"    {rng.choice(_BRANCHES)} {rs1}, {rs2}, {label}")
            lines.extend(straight() for _ in range(rng.randrange(4)))
            lines.append(f"{label}:")
        elif kind == "jal":
            label = f"L{labels}"
            labels += 1
            lines.append(f"    jal {reg()}, {label}")
            lines.extend(straight() for _ in range(rng.randrange(4)))
            lines.append(f"{label}:")
        else:  # jalr: AUIPC holds this PC; JALR lands two instructions later, skipping one
            lines.append(f"    auipc {_JUMP_BASE}, 0")
            lines.append(f"    jalr {reg()}, 12({_JUMP_BASE})")
            lines.append(straight())

    lines.extend(f"    xor x5, x5, {r}" for r in _WORK_REGISTERS if r != "x5")
    lines.extend([  # x17, not t0: t0 is x5, the value being output
        f"    li x17, {_OUT_ADDR:#x}",
        "    sw x5, 0(x17)",
        "    ebreak",
        "",
    ])
    return "\n".join(lines)
