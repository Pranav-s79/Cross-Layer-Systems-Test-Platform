"""Deterministic, terminating RV32I programs for seeded differential tests."""

from __future__ import annotations

import random
from typing import Callable

_WORK_REGISTERS = tuple(f"x{i}" for i in range(5, 16) if i != 8)
_JUMP_BASE = "x16"
"""Holds the PC for an AUIPC + JALR pair; never a work register."""
_BINARY_OPS = ("add", "sub", "sll", "slt", "sltu", "xor", "srl", "sra", "or", "and")
_IMMEDIATE_OPS = ("addi", "slti", "sltiu", "xori", "ori", "andi")
_SHIFT_OPS = ("slli", "srli", "srai")
_LOADS = {"lb": 1, "lbu": 1, "lh": 2, "lhu": 2, "lw": 4}
_STORES = {"sb": 1, "sh": 2, "sw": 4}
_BRANCHES = ("beq", "bne", "blt", "bge", "bltu", "bgeu")
_MEMORY_BYTES = 64 * 1024
_SCRATCH_BASE = 0x4000
_SCRATCH_BYTES = 256
_OUT_ADDR = 0x1000_0000
_WEIGHTS = {"alu": 6, "imm": 4, "shift": 2, "upper": 1, "load": 3, "store": 3, "branch": 3, "jal": 1, "jalr": 1}

MIXES = ("uniform", "hazards")
"""Instruction mixes: ``uniform`` picks every register independently;
``hazards`` makes nearby instructions depend on each other (see ``generate``)."""
_HAZARD_WEIGHTS = {**_WEIGHTS, "load_use": 3, "compute_branch": 2, "compute_store": 2, "chain": 3}
_DEPENDENT_SOURCE = 0.6
"""In the hazards mix, the chance that a source operand is a recent result."""


def generate(seed: int, *, instructions: int = 300, mix: str = "uniform") -> str:
    """Return a reproducible, bounded RV32I assembly program.

    Every working register is initialized first. Data accesses stay inside an
    aligned scratch area and are naturally aligned for their width (each byte
    offset a width allows is used). Control flow only goes forward: branches
    and jumps skip 0-3 instructions, and JALR jumps over one instruction via
    AUIPC, so every program terminates. A quarter of the branches compare a
    register with itself, so every branch is both taken and not taken across
    seeds. All working registers are XOR-folded into the single output value,
    so any wrong result reaches the output port, and EBREAK ends the program.
    ECALL is never generated (it would end the run early).

    ``mix="hazards"`` targets a pipeline's forwarding, stall, and flush logic:
    a source operand is one of the last three results with probability 0.6,
    and four patterns are added: a load whose result the next (or the one
    after) instruction uses, a computed value that a branch tests at once, a
    computed value stored at once, and a chain of three dependent operations.
    The default ``uniform`` mix is unchanged, so existing seeds keep their
    programs.

    ``instructions`` counts generated body items; a branch, jump, or pattern
    item emits several instructions.
    """
    if isinstance(seed, bool) or not isinstance(seed, int):
        raise TypeError("seed must be an integer")
    if isinstance(instructions, bool) or not isinstance(instructions, int) or instructions < 1:
        raise ValueError("instructions must be a positive integer")
    if mix not in MIXES:
        raise ValueError(f"mix must be one of {list(MIXES)}")
    if _SCRATCH_BASE + _SCRATCH_BYTES > _MEMORY_BYTES:
        raise AssertionError("random-program scratch area exceeds testbench memory")

    rng = random.Random(seed)
    lines = [
        f"# Generated by CrossLayer with seed {seed}" + (f" ({mix} mix)." if mix != "uniform" else "."),
        ".text",
        ".globl _start",
        "_start:",
        f"    li s0, {_SCRATCH_BASE}",
    ]
    for register in _WORK_REGISTERS:
        lines.append(f"    li {register}, {rng.randrange(0, 1 << 32)}")

    (_uniform_body if mix == "uniform" else _hazard_body)(rng, instructions, lines)

    lines.extend(f"    xor x5, x5, {r}" for r in _WORK_REGISTERS if r != "x5")
    lines.extend([  # x17, not t0: t0 is x5, the value being output
        f"    li x17, {_OUT_ADDR:#x}",
        "    sw x5, 0(x17)",
        "    ebreak",
        "",
    ])
    return "\n".join(lines)


def _uniform_body(rng: random.Random, instructions: int, lines: list[str]) -> None:
    kinds = list(_WEIGHTS)
    weights = list(_WEIGHTS.values())

    def reg() -> str:
        return rng.choice(_WORK_REGISTERS)

    def straight() -> str:
        """One instruction that never changes control flow or touches memory."""
        return f"    {rng.choice(_BINARY_OPS)} {reg()}, {reg()}, {reg()}"

    labels = 0
    for _ in range(instructions):
        kind = rng.choices(kinds, weights)[0]
        if kind == "alu":
            lines.append(f"    {rng.choice(_BINARY_OPS)} {reg()}, {reg()}, {reg()}")
        elif kind == "imm":
            lines.append(f"    {rng.choice(_IMMEDIATE_OPS)} {reg()}, {reg()}, {rng.randint(-2048, 2047)}")
        elif kind == "shift":
            lines.append(f"    {rng.choice(_SHIFT_OPS)} {reg()}, {reg()}, {rng.randrange(32)}")
        elif kind == "upper":
            lines.append(f"    {rng.choice(('lui', 'auipc'))} {reg()}, {rng.randrange(1 << 20)}")
        elif kind in ("load", "store"):
            op, size = rng.choice(list((_LOADS if kind == "load" else _STORES).items()))
            offset = size * rng.randrange(_SCRATCH_BYTES // size)
            lines.append(f"    {op} {reg()}, {offset}(s0)")
        elif kind == "branch":
            rs1 = reg()
            rs2 = rs1 if rng.random() < 0.25 else reg()
            label = f"L{labels}"
            labels += 1
            lines.append(f"    {rng.choice(_BRANCHES)} {rs1}, {rs2}, {label}")
            lines.extend(straight() for _ in range(rng.randrange(4)))
            lines.append(f"{label}:")
        elif kind == "jal":
            label = f"L{labels}"
            labels += 1
            lines.append(f"    jal {reg()}, {label}")
            lines.extend(straight() for _ in range(rng.randrange(4)))
            lines.append(f"{label}:")
        else:  # jalr: AUIPC holds this PC; JALR lands two instructions later, skipping one
            lines.append(f"    auipc {_JUMP_BASE}, 0")
            lines.append(f"    jalr {reg()}, 12({_JUMP_BASE})")
            lines.append(straight())


def _hazard_body(rng: random.Random, instructions: int, lines: list[str]) -> None:
    """Like the uniform body, but operands favor the last few results and
    hazard patterns are mixed in. Sources are chosen before the destination,
    so an instruction depends on earlier ones, not on itself."""
    kinds = list(_HAZARD_WEIGHTS)
    weights = list(_HAZARD_WEIGHTS.values())
    recent: list[str] = []  # destinations of the last few instructions, newest last
    labels = 0

    def reg() -> str:
        return rng.choice(_WORK_REGISTERS)

    def src() -> str:
        if recent and rng.random() < _DEPENDENT_SOURCE:
            return rng.choice(recent)
        return reg()

    def wrote(register: str) -> str:
        recent.append(register)
        del recent[:-3]
        return register

    def op3(ops: tuple[str, ...], a: Callable[[], str] = src, b: Callable[[], str] = src) -> str:
        """``op rd, a, b`` with the sources picked first."""
        x, y = a(), b()
        return f"    {rng.choice(ops)} {wrote(reg())}, {x}, {y}"

    def access(kind: str, register: str) -> str:
        op, size = rng.choice(list((_LOADS if kind == "load" else _STORES).items()))
        return f"    {op} {register}, {size * rng.randrange(_SCRATCH_BYTES // size)}(s0)"

    def skip_block(head: str) -> None:
        nonlocal labels
        label = f"L{labels}"
        labels += 1
        lines.append(head.format(label=label))
        lines.extend(op3(_BINARY_OPS) for _ in range(rng.randrange(4)))
        lines.append(f"{label}:")

    for _ in range(instructions):
        kind = rng.choices(kinds, weights)[0]
        if kind == "alu":
            lines.append(op3(_BINARY_OPS))
        elif kind == "imm":
            x = src()
            lines.append(f"    {rng.choice(_IMMEDIATE_OPS)} {wrote(reg())}, {x}, {rng.randint(-2048, 2047)}")
        elif kind == "shift":
            x = src()
            lines.append(f"    {rng.choice(_SHIFT_OPS)} {wrote(reg())}, {x}, {rng.randrange(32)}")
        elif kind == "upper":
            lines.append(f"    {rng.choice(('lui', 'auipc'))} {wrote(reg())}, {rng.randrange(1 << 20)}")
        elif kind == "load":
            lines.append(access("load", wrote(reg())))
        elif kind == "store":
            lines.append(access("store", src()))
        elif kind == "branch":
            rs1 = src()
            rs2 = rs1 if rng.random() < 0.25 else src()
            skip_block(f"    {rng.choice(_BRANCHES)} {rs1}, {rs2}, {{label}}")
        elif kind == "jal":
            skip_block(f"    jal {wrote(reg())}, {{label}}")
        elif kind == "jalr":
            lines.append(f"    auipc {_JUMP_BASE}, 0")
            lines.append(f"    jalr {wrote(reg())}, 12({_JUMP_BASE})")
            lines.append(op3(_BINARY_OPS))
        elif kind == "load_use":  # the next instruction, or the one after, uses the loaded value
            loaded = reg()
            lines.append(access("load", wrote(loaded)))
            if rng.random() < 0.3:
                lines.append(op3(_BINARY_OPS))
            lines.append(op3(_BINARY_OPS, lambda: loaded) if rng.random() < 0.5 else op3(_BINARY_OPS, b=lambda: loaded))
        elif kind == "compute_branch":  # the branch tests a value computed just before
            lines.append(op3(_BINARY_OPS))
            tested = recent[-1]
            skip_block(f"    {rng.choice(_BRANCHES)} {tested}, {src()}, {{label}}")
        elif kind == "compute_store":  # the store writes a value computed just before
            lines.append(op3(_BINARY_OPS))
            lines.append(access("store", recent[-1]))
        else:  # chain: three operations, each using the result before it
            for _ in range(3):
                lines.append(op3(_BINARY_OPS, lambda: recent[-1] if recent else reg()))
